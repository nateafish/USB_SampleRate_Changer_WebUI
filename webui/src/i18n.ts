export function translate(language: Language, value: string): string {
  return language === "en" ? english[value] ?? value : value;
}

export function translateRuntime(language: Language, value: string): string {
  if (language !== "en") return value;
  if (value.startsWith("Error: ")) {
    const translated = translateRuntime(language, value.slice(7));
    return translated === value.slice(7) ? value : `Error: ${translated}`;
  }
  const exact = translate(language, value);
  if (exact !== value) return exact;
  const patterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^应用失败，退出码 (.+)$/, (m) => `Apply failed, exit code ${m[1]}`],
    [/^重置失败，退出码 (.+)$/, (m) => `Reset failed, exit code ${m[1]}`],
    [/^执行失败，退出码 (.+)$/, (m) => `Operation failed, exit code ${m[1]}`],
    [/^诊断失败，退出码 (.+)$/, (m) => `Diagnostics failed, exit code ${m[1]}`],
    [/^([^ ]+) 执行失败，退出码 (.+)$/, (m) => `${m[1]} failed, exit code ${m[2]}`],
    [/^(.+)已完成，但 A2DP 路由检查失败，蓝牙媒体音频可能已经失效。需要打开蓝牙设置以断开并重新连接设备。$/, (m) => `${english[m[1]] ?? m[1]} completed, but the A2DP route check failed and Bluetooth media audio may be unavailable. Bluetooth settings are required to disconnect and reconnect the device.`],
    [/^Error: (.+)$/, (m) => `Error: ${m[1]}`]
  ];
  for (const [pattern, format] of patterns) {
    const match = value.match(pattern);
    if (match) return format(match);
  }
  return value;
}
